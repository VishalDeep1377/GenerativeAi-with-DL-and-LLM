# Progressive-resolution GAN demonstration for MNIST (7x7, 14x14, 28x28)
import numpy as np
import tensorflow as tf
import matplotlib.pyplot as plt
from tensorflow.keras import layers

(x_train, _), (_, _) = tf.keras.datasets.mnist.load_data()
x_train = (x_train.astype("float32") - 127.5) / 127.5
x_train = np.expand_dims(x_train, axis=-1)

def create_generator(resolution):
    model = tf.keras.Sequential([layers.Input(shape=(100,)), layers.Dense(7 * 7 * 128), layers.Reshape((7, 7, 128)), layers.BatchNormalization(), layers.ReLU()])
    if resolution >= 14:
        model.add(layers.Conv2DTranspose(64, 4, strides=2, padding="same")); model.add(layers.BatchNormalization()); model.add(layers.ReLU())
    if resolution >= 28:
        model.add(layers.Conv2DTranspose(32, 4, strides=2, padding="same")); model.add(layers.BatchNormalization()); model.add(layers.ReLU())
    model.add(layers.Conv2D(1, 3, padding="same", activation="tanh"))
    return model

def create_discriminator(resolution):
    return tf.keras.Sequential([layers.Input(shape=(resolution, resolution, 1)), layers.Conv2D(64, 4, strides=2, padding="same"), layers.LeakyReLU(0.2), layers.Conv2D(128, 4, strides=2, padding="same"), layers.LeakyReLU(0.2), layers.Flatten(), layers.Dense(1)])

def train_gan(resolution, epochs=2, batch_size=128):
    images = tf.image.resize(x_train, [resolution, resolution])
    dataset = tf.data.Dataset.from_tensor_slices(images).shuffle(10000).batch(batch_size, drop_remainder=True)
    generator, discriminator = create_generator(resolution), create_discriminator(resolution)
    loss_fn = tf.keras.losses.BinaryCrossentropy(from_logits=True)
    g_opt = tf.keras.optimizers.Adam(0.0002, beta_1=0.5); d_opt = tf.keras.optimizers.Adam(0.0002, beta_1=0.5)
    @tf.function
    def train_step(real_images):
        noise = tf.random.normal([tf.shape(real_images)[0], 100])
        with tf.GradientTape() as gt, tf.GradientTape() as dt:
            fake = generator(noise, training=True)
            real_out = discriminator(real_images, training=True); fake_out = discriminator(fake, training=True)
            g_loss = loss_fn(tf.ones_like(fake_out), fake_out)
            d_loss = loss_fn(tf.ones_like(real_out), real_out) + loss_fn(tf.zeros_like(fake_out), fake_out)
        g_opt.apply_gradients(zip(gt.gradient(g_loss, generator.trainable_variables), generator.trainable_variables))
        d_opt.apply_gradients(zip(dt.gradient(d_loss, discriminator.trainable_variables), discriminator.trainable_variables))
        return g_loss, d_loss
    for epoch in range(epochs):
        for batch in dataset: g_loss, d_loss = train_step(batch)
        print("Resolution:", resolution, "Epoch:", epoch + 1, "Generator Loss:", float(g_loss), "Discriminator Loss:", float(d_loss))
    return generator

generator_7 = train_gan(7, 2)
generator_14 = train_gan(14, 2)
generator_28 = train_gan(28, 3)
images = generator_28(tf.random.normal([16, 100]), training=False)
plt.figure(figsize=(8, 8))
for i in range(16):
    plt.subplot(4, 4, i + 1); plt.imshow((images[i, :, :, 0] + 1) / 2, cmap="gray"); plt.axis("off")
plt.suptitle("Images Generated by Progressive GAN"); plt.show()
